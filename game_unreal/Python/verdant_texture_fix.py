"""Texture pass of 15 November 2026 (the entrant saw imperfect textures in the trailer). One writer job, run through
verdant/run_unreal.ps1 -NoRender with -TextureFixApply:

  paving   re-imports T_V_Cobble_* and T_V_Flagstone_* from output/verdant/textures (regenerated by
           verdant/make_verdant_textures.py -- cobble flagstone) and rebuilds M_V_Cobble and M_V_Flagstone
           (verdant_materials.paving) with their Present instances.
  land     rebuilds M_V_Land (verdant_materials.land) with its mid-scale breakup.
  ruin     the family home's ruined wall (StaticMeshActor_14, SM_Home_Ruin) wore the Quest-era M_PhotoQuestLimewash on
           slot 1, which renders as bare white boards. That slot gets the owned, box-mapped
           /Game/Quest/XR/VisualPass/M_Home_RuinPlaster (weathered plaster breaking to stone). Slot only: no mesh,
           transform, tag, collision or era wiring changes. The map is saved.

Before anything is written the affected .uasset/.umap files are copied once to
game_unreal/validation/texture_fix/original_20261115/ (the revert is: close the editor, copy them back). The run's
record (hashes before and after, the slot's previous material) is game_unreal/validation/texture_fix/applied_record.json.
Nothing outside /Game/Verdant, /Game/Quest/XR/VisualPass and the story map is touched.
"""
import hashlib
import json
import shutil
import sys
import traceback
from datetime import datetime, timezone
from pathlib import Path

import unreal

sys.path.insert(0, str(Path(unreal.Paths.project_dir()).resolve() / 'Python'))
import verdant_common as vc
import verdant_materials as vm

if not vc.has_flag('TextureFixApply'):
    raise RuntimeError('-TextureFixApply is required (this job writes assets and the story map)')
PROJECT = vc.PROJECT
MAP = '/Game/Quest/Maps/Verdant_Desktop'
PASS_PATH = '/Game/Quest/XR/VisualPass'
OUT = PROJECT / 'validation' / 'texture_fix'
ORIGINAL = OUT / 'original_20261115'
RECORD = OUT / 'applied_record.json'
STAMP = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')
TEXTURES = ['T_V_Cobble_BC', 'T_V_Cobble_N', 'T_V_Cobble_ARH', 'T_V_Flagstone_BC', 'T_V_Flagstone_N', 'T_V_Flagstone_ARH']
FILES = ['Content/Verdant/Textures/%s.uasset' % t for t in TEXTURES] + \
        ['Content/Verdant/Materials/%s.uasset' % m for m in ('M_V_Cobble', 'M_V_Flagstone', 'M_V_Land', 'MI_V_Cobble_Present', 'MI_V_Flagstone_Present')] + \
        ['Content/Quest/Maps/Verdant_Desktop.umap']
RUIN_ACTOR, RUIN_SLOT, RUIN_MATERIAL = 'StaticMeshActor_14', 1, 'M_Home_RuinPlaster'
SETTINGS = unreal.TextureCompressionSettings
REPORT = {'success': False, 'stamp': STAMP, 'files': {}, 'ruin': {}}


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest() if Path(path).exists() else None


def import_texture(name):
    task = unreal.AssetImportTask()
    for key, value in (('filename', str(vc.SOURCE / 'textures' / (name + '.png'))), ('destination_path', vc.ROOT_PATH + '/Textures'),
                       ('destination_name', name), ('automated', True), ('save', False), ('replace_existing', True), ('replace_existing_settings', True)):
        task.set_editor_property(key, value)
    vc.assets.import_asset_tasks([task])
    texture = unreal.load_asset(vc.ROOT_PATH + '/Textures/' + name)
    vc.require(texture is not None, 'Import failed: ' + name)
    if name.endswith('_N'):
        texture.set_editor_property('compression_settings', SETTINGS.TC_NORMALMAP)
        texture.set_editor_property('srgb', False)
        texture.set_editor_property('flip_green_channel', False)
    elif name.endswith('_ARH'):
        texture.set_editor_property('compression_settings', SETTINGS.TC_MASKS)
        texture.set_editor_property('srgb', False)
    else:
        texture.set_editor_property('compression_settings', SETTINGS.TC_BC7)
        texture.set_editor_property('srgb', True)
    vc.library.save_loaded_asset(texture)


def ruin_material():
    """Weathered plaster breaking to stone, sampled in world space (the home meshes' own UVs stretch on these blocks)."""
    saved = vm.PATH
    vm.PATH = PASS_PATH
    try:
        g = vm.Graph(RUIN_MATERIAL)
        wp, n = g.world(), g.vnormal()
        uv = g.custom(vm.BOX_UV, {'P': wp, 'N': n, 'Tile': g.scalar('TileCm', 320)}, vm.FLOAT2)
        plaster, stone = g.sample('T_V_Plaster_BC', uv), g.sample('T_V_Limestone_BC', uv)
        mask = g.masks('T_V_Masks', g.custom('return UV * .37 + float2(.17, .53);', {'UV': uv}, vm.FLOAT2))
        broad = g.masks('T_V_Masks', g.custom('return UV * .09 + float2(.41, .23);', {'UV': uv}, vm.FLOAT2))
        colour = g.custom('''
// Plaster has come away in patches; the stone under it shows, darker.
float loss = saturate((Mask.r * .7 + Broad.r * .3 - (1.0 - Loss)) * 6.0);
float3 c = lerp(Plaster * Tint.rgb, Stone * float3(.78, .74, .68), loss);
c *= lerp(.76, 1.06, Broad.r);
c *= lerp(1.0, .78, saturate(Mask.g * 1.5 - .55));
return c * Brightness;
''', {'Plaster': plaster, 'Stone': stone, 'Mask': mask, 'Broad': broad, 'Tint': g.vector('Tint', (.93, .86, .74, 1)),
      'Loss': g.scalar('Loss', .44), 'Brightness': g.scalar('Brightness', 1.0)})
        g.out(vm.BC, colour)
        g.out(vm.ROUGH, g.scalar('Roughness', .9))
        g.out(vm.SPEC, g.scalar('Specular', .25))
        return g.done()
    finally:
        vm.PATH = saved


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    before = {f: digest(PROJECT / f) for f in FILES}
    if not ORIGINAL.exists():
        ORIGINAL.mkdir(parents=True)
        for f in FILES:
            target = ORIGINAL / f
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(PROJECT / f, target)
        vc.write_json(ORIGINAL / 'sha256.json', before)
        REPORT['original_backup_written'] = True
    for name in TEXTURES:
        import_texture(name)
    cobble = vm.paving('M_V_Cobble', 'T_V_Cobble', 400)
    flagstone = vm.paving('M_V_Flagstone', 'T_V_Flagstone', 600)
    vm.instance(cobble, 'MI_V_Cobble_Present', {'Aging': .55, 'Weeds': .9})
    vm.instance(flagstone, 'MI_V_Flagstone_Present', {'Aging': .55, 'Weeds': .75})
    vm.land()
    plaster = ruin_material()
    vc.require(vc.levels.load_level(MAP), 'Cannot load ' + MAP)
    actor = next((a for a in vc.actors.get_all_level_actors() if a.get_name() == RUIN_ACTOR), None)
    vc.require(actor is not None, 'Missing ' + RUIN_ACTOR)
    component = actor.get_component_by_class(unreal.StaticMeshComponent)
    current = component.get_material(RUIN_SLOT)
    previous = json.loads(RECORD.read_text(encoding='utf-8')).get('ruin', {}) if RECORD.exists() else {}
    REPORT['ruin'] = {'actor': RUIN_ACTOR, 'label': actor.get_actor_label(), 'slot': RUIN_SLOT,
                      'before': previous.get('before') or (current.get_path_name() if current else None),
                      'after': plaster.get_path_name(), 'slots': component.get_num_materials()}
    if current is None or current.get_path_name() != plaster.get_path_name():
        component.set_material(RUIN_SLOT, plaster)
        vc.require(vc.levels.save_current_level(), 'Cannot save the map')
        REPORT['ruin']['map_saved'] = True
    else:
        REPORT['ruin']['map_saved'] = False
    REPORT['files'] = {f: {'before': before[f], 'after': digest(PROJECT / f)} for f in FILES}
    REPORT['new_assets'] = [PASS_PATH + '/' + RUIN_MATERIAL]
    REPORT['original_backup'] = str(ORIGINAL)
    REPORT['success'] = True


try:
    main()
except Exception:
    REPORT['error'] = traceback.format_exc()
if REPORT['success']:
    vc.write_json(RECORD, REPORT)
vc.write_json(OUT / (STAMP + '_report.json'), REPORT)
vc.log('texture fix finished', json.dumps({'success': REPORT['success'], 'ruin': REPORT.get('ruin'), 'error': (REPORT.get('error') or '')[-600:]}))
unreal.SystemLibrary.quit_editor()
